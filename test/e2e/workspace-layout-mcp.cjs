const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {McpClient}=require('../../tools/mcp/client.cjs');
(async()=>{
 const c=new McpClient();await c.start();let checks=0;
 const call=async(name,args={})=>{const r=await c.call(name,args);if(r.isError)throw Error(r.text);return r.json};
 const ev=code=>call('js_eval',{code});
 const check=(ok,label)=>{assert.ok(ok,label);checks++;console.log('확인',label)};
 const wait=code=>call('ui_wait',{code,timeoutMs:10000});
 try{
  await call('app_start',{build:'never',width:1100,height:840,prep:'test'});
  await call('app_mode',{mode:'music'});
  check((await wait('!!document.querySelector("[data-testid=workspace-development-tts]")')).met,'새 콘텐츠 작업의 개발 중 표시');
  await call('ui_click',{target:'testid:workspace-arrange'});
  await call('ui_pointer',{target:'testid:workspace-position-tts',action:'drag',toTarget:'testid:workspace-position-conversation',steps:20});
  check((await wait('!!document.querySelector("[data-testid=workspace-group-files] [data-testid=mode-tts]")')).met,'실제 마우스 드래그로 상단 분류 이동');
  check(await ev('!document.querySelector("[data-testid=workspace-development-tts]")'),'이동하면 개발 중 표시 제거');
  check(await ev('window.__afStore.getState().mode==="music"'),'배치 이동이 작업 화면을 바꾸지 않음');
  let r=await ev('window.api.options.getWorkspaceLayout()');check(r.ok&&r.layout.files[1]==='tts','메뉴 순서 실제 저장');
  const opts=await ev('window.api.options.get()');const settingsPath=path.join(opts.dataDir,'settings.json');
  const saved=fs.readFileSync(settingsPath,'utf8');
  fs.writeFileSync(settingsPath,'{깨진 설정');
  await call('ui_click',{target:'testid:workspace-up-tts'});
  check((await wait('document.querySelector("[data-testid=workspace-sidebar]")?.textContent.includes("저장하지 못했습니다")')).met,'저장 실패 표시');
  check(await ev('document.querySelector("[data-testid=workspace-group-files]").querySelectorAll(".workspace-nav-item")[1].dataset.testid==="mode-tts"'),'저장 실패 시 기존 배치 유지');
  check(fs.readFileSync(settingsPath,'utf8')==='{깨진 설정','손상된 설정을 덮지 않음');
  fs.writeFileSync(settingsPath,saved);
  await call('ui_click',{target:'testid:workspace-up-tts'});
  check((await wait('document.querySelector("[data-testid=workspace-group-files]").querySelector(".workspace-nav-item").dataset.testid==="mode-tts"')).met,'실패 뒤 다시 이동하면 정상 저장');
  await ev('(()=>{window.__afStore.setState({status:"processing"});return true})()');
  check(await ev('document.querySelector("[data-testid=workspace-up-tts]").disabled'),'생성 중 배치 변경 차단');
  await ev('(()=>{window.__afStore.setState({status:"idle"});return true})()');
  await wait('!document.querySelector("[data-testid=workspace-up-tts]").disabled');
  await call('ui_screenshot',{savePath:'workspace-layout-wide.png'});
  await call('app_reload');
  await call('app_mode',{mode:'music'});
  check((await wait('document.querySelector("[data-testid=workspace-group-files]")?.querySelector(".workspace-nav-item")?.dataset.testid==="mode-tts"')).met,'화면 재로딩 후 저장 배치 복원');
  if(await ev('document.querySelector("[data-testid=workspace-arrange]").getAttribute("aria-pressed")!=="true"')) await call('ui_click',{target:'testid:workspace-arrange'});
  check((await wait('!!document.querySelector("[data-testid=workspace-drop-create]")')).met,'배치 편집 도구 열기');
  await call('ui_scroll',{target:'testid:workspace-sidebar',to:'bottom'});
  await call('ui_pointer',{target:'testid:workspace-position-tts',action:'drag',toTarget:'testid:workspace-position-reader',steps:20});
  check((await wait('!!document.querySelector("[data-testid=workspace-development-tts]")')).met,'하단으로 돌려놓으면 개발 중 복원');
  r=await ev('window.api.options.setWorkspaceLayout({version:1,files:["tts"],create:["tts"]})');check(!r.ok,'누락·중복 배치 본체 거절');
  await call('window_resize',{width:760,height:700});
  check(await ev('(()=>{const e=document.querySelector("[data-testid=workspace-sidebar]");return e.scrollWidth<=e.clientWidth})()'),'좁은 창 메뉴 가로 넘침 없음');
  await call('ui_screenshot',{savePath:'workspace-layout-small.png'});
  const errors=await call('errors');check(errors.count===0,'화면 오류 없음');
  console.log(JSON.stringify({checks,errors}));
 }finally{await c.call('app_stop');await c.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
