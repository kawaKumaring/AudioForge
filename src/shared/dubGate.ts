/**
 * 더빙 화면에서 **단추가 왜 잠겼는지** 한 곳에서 정한다.
 *
 * ★왜(2026-09-25 사용자 신고: "영상에 목소리 쓰기를 하지 못한다")
 *   `영상 속 목소리 쓰기` 는 앞단이 끝나야 쓸 수 있다. 그런데 화면은
 *   **흐릿해진 단추 하나만** 보여 주고 이유를 한 글자도 말하지 않았다.
 *   사용자는 "고장났다" 로 읽는다 — 실제로는 순서가 남아 있을 뿐인데.
 *
 *   더 나쁜 것은, 앞단을 **이미 다 끝내 놓은** 경우다. 결과는 작업 폴더에
 *   그대로 있는데, 앱을 껐다 켜면 화면이 그것을 모른다. 되살리는 길은
 *   **영상을 다시 고르는 것** 하나뿐인데 그 사실이 어디에도 안 적혀 있었다.
 *
 * 이 파일은 **문구만** 만든다. 화면 그리기도, 부르기도 하지 않는다.
 */

export interface DubUseOriginalState {
  /** 지금 고른 영상. 비어 있으면 아직 안 골랐다. */
  videoPath: string
  /** 앞단 결과가 화면에 올라와 있는가. */
  frontLoaded: boolean
  /** 다른 작업이 도는 중인가. */
  busy: boolean
}

/**
 * 잠긴 이유. 쓸 수 있으면 빈 문자열.
 *
 * ★순서가 중요하다 — 사용자가 **다음에 할 일**을 말해야 한다.
 *   "앞단을 끝내세요" 를 영상도 안 고른 사람에게 하면 길을 잃는다.
 */
export function useOriginalBlockReason(s: DubUseOriginalState): string {
  if (s.busy) return '지금 돌고 있는 작업이 끝나면 쓸 수 있습니다.'
  if (!s.videoPath) return '먼저 영상을 고르세요.'
  if (!s.frontLoaded) {
    return '먼저 시작을 눌러 앞단을 끝내세요 — 영상에서 목소리를 갈라내야 그것을 쓸 수 있습니다.'
  }
  return ''
}

/**
 * 앞단을 끝내 놓고 앱을 다시 켠 사람에게 주는 길잡이.
 * ★이 한 줄이 없어서, 다 해 놓은 작업을 처음부터 다시 돌릴 뻔했다.
 */
export const DUB_RESUME_HINT =
  '지난번에 앞단을 끝냈다면 영상을 다시 고르면 그대로 이어집니다 — 다시 돌리지 않아도 됩니다.'
