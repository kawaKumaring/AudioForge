/**
 * **소리로 내지 않는 기호** — 한 곳의 규칙. 파이썬 짝은 `python/speech_symbols.py` 이고,
 * 두 쪽이 같은 답을 내는지는 `speechSymbols.cases.json` 한 벌로 둘 다 검사한다(갈라지면 울린다).
 *
 * ★왜 (2026-09-30 사용자 신고 두 번)
 *   1) "' \" * 같은 특수기호를 소리 내려고 '에 에 에' 하는 소리를 낸다."
 *   2) "............. ///// !!!!! ******* ''''' \"\"\"\"\" ~~~~~ ------ +++++++ [[[[ ]]]]]]] (((((( )))))) 등으로
 *      소리를 내려고 하는 게 있으면 막아라."
 *   모델은 모르는 기호·기호 뭉치를 억지로 소리로 만든다. 뜻이 없는 기호는 빼고, 뜻이 있는 문장 부호는 한 번만 남긴다.
 *
 * 규칙
 *   - 늘 빼는 것: 따옴표 · 별표 · 괄호류([ ] < > 【 】 「 」) · 꾸밈 기호(♡ ★ ◆ ※ ♪) · 밑줄 · 빗금 · # @ = + | \ ^ `
 *     — 기호만 빼고 **안의 글은 읽는다**("누구세요?" → 누구세요?).
 *   - 한 번만 남기는 것(쉼·억양을 만든다): 마침표 여럿·말줄임 → …, !!!! → !, ???? → ?, ?!?! → ?, 쉼표·쌍점 여럿 → 하나.
 *   - 하이픈은 낱말·숫자 안(e-mail · 010-1234)에서만 남긴다. 줄표 뭉치(------ · ———)와 홀로 선 줄표는 뺀다.
 *   - 괄호는 하나씩 짝을 이룬 것만 남긴다((웃음)). 겹친 괄호((((( · ))))))와 빈 괄호 ()는 뺀다.
 *   - 물결표: 숫자 사이는 범위(10~20명 → 10에서 20명), 나머지는 뺀다.
 *   - 영어 낱말 안의 작은따옴표(don't)는 남긴다.
 *   - 빼고 나서 **읽을 글자가 없으면 빈 글** — 부르는 쪽이 소리 없이 건너뛴다(장면 구분 줄 등).
 */
const SILENT = /["“”„‟«»‹›「」『』〈〉《》【】〔〕\[\]{}<>*＊_＿`´^|\\/＼#＃@=＝+＋♡♥☆★◆◇■□●○◎▲△▼▽※→←↑↓↔♪♬♩♫]/g
/** 글자로 둘러싸이지 않은 작은따옴표 — 여는/닫는 따옴표로 쓰인 것. */
const LONE_QUOTE = /(?<![A-Za-z])['‘’‚‛]|['‘’‚‛](?![A-Za-z])/g
const RANGE_TILDE = /(\d)\s*[~～〜]\s*(\d)/g
const TILDE = /[~～〜]/g
/** 마침표 둘 이상(사이 띄어쓰기 포함)·말줄임 여럿 → 말줄임 하나. */
const DOTS = /[.…](?:[ \t]*[.…])+/g
const BANG_QUESTION = /([!?！？])[!?！？ \t]*[!?！？]/g
const COMMAS = /([,，;:])(?:[ \t]*[,，;:])+/g
/** 낱말·숫자 안의 하이픈은 남기고, 나머지 줄표·하이픈은 뺀다. */
const DASH = /(?<![\p{L}\p{N}])[-‐‑‒–—―─━]+|[-‐‑‒–—―─━]+(?![\p{L}\p{N}])|[-‐‑‒–—―─━]{2,}/gu
const PAREN_RUN = /[(（]{2,}|[)）]{2,}|[(（]\s*[)）]/g

/** 기호를 뺀 뒤 띄어쓰기를 고른다 — 부호 앞의 빈칸, 겹친 빈칸, 줄 앞뒤. */
function tidy(s: string): string {
  return s.replace(/[ \t]{2,}/g, ' ').replace(/[ \t]+([.,!?…;:)）])/g, '$1').replace(/([(（])[ \t]+/g, '$1')
    .split('\n').map((l) => l.trim()).join('\n').trim()
}

export function stripSpokenSymbols(text: string): string {
  let s = text.replace(RANGE_TILDE, '$1에서 $2').replace(TILDE, ' ')
  s = s.replace(PAREN_RUN, ' ').replace(SILENT, ' ').replace(LONE_QUOTE, ' ').replace(DASH, ' ')
  s = s.replace(DOTS, '…').replace(BANG_QUESTION, '$1').replace(COMMAS, '$1')
  // 빼고 나서 괄호가 비었으면 그것도 뺀다("( * )" → "").
  s = s.replace(/[(（]\s*[)）]/g, ' ')
  s = tidy(s)
  return /[\p{L}\p{N}]/u.test(s) ? s : ''
}
