/**
 * 화면에 보일 `분:초.십분의일` 표기 — **한 곳에서만 계산한다.**
 *
 * ★왜 모았나(2026-09-24 2차 감사)
 *   같은 계산이 **네 곳**에 따로 있었고 넷 다 같은 방식으로 틀렸다.
 *   분을 `Math.floor(초/60)` 로 **먼저 확정**한 뒤 나머지를 반올림해서,
 *   **자리올림이 분으로 전파되지 않았다.**
 *
 *   실측 — 59.96초가 `0:60.0`, 119.97초가 `1:60.0` 으로 보인다.
 *   더빙 쪽은 0 채움 판정까지 반올림 전 값으로 해서 9.96초가 `0:010.0` 이 됐다.
 *   저장되는 파일은 정상이고 **표시만** 틀린다.
 *
 *   발생 창이 분당 0.05~0.1초로 좁아 이따금 나온다 — 그래서 오래 남아 있었다.
 *
 *   ★같은 저장소의 `analysisWording.ts` 와 파이썬 `audio_utils.fmt_time` 은
 *     **먼저 반올림해** 이 문제를 이미 피하고 있었다. 즉 옳은 공식이 이미 있었는데
 *     네 곳이 각자 다시 짰다. 같은 계산을 여러 곳에 두지 않는다.
 */

/**
 * `분:초.십분의일`. 음수는 0으로 본다.
 *
 * **먼저 십분의 일 단위로 반올림한 뒤** 분을 가른다 — 그래야 자리올림이 분까지 간다.
 */
export function formatMinSec(sec: number): string {
  const n = Number(sec)
  const tenths = Number.isFinite(n) ? Math.round(Math.max(0, n) * 10) : 0
  const m = Math.floor(tenths / 600)
  const rest = (tenths % 600) / 10
  return `${m}:${rest.toFixed(1).padStart(4, '0')}`
}
